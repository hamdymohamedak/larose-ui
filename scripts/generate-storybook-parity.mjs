#!/usr/bin/env node
/**
 * Generate Storybook cross-framework parity artifacts from package indexes + contracts.
 *
 * Outputs:
 * - apps/playground/cross-framework/generated/vuePackageComponents.ts
 * - apps/playground/cross-framework/generated/sveltePackageComponents.ts
 * - apps/playground/.storybook/crossFramework/registry/generated.tsx
 * - apps/playground/.storybook/crossFramework/titleRegistry.generated.ts
 * - apps/playground/stories/generated/AutoParity.stories.tsx
 * - apps/playground/.storybook/crossFramework/catalog.json
 *
 * Hand-written registry / demos always win over generated entries.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildStorybookCatalog,
  parseDefaultExportPaths,
  pickSimplePropKeys,
  readComponentContract,
  defaultValueForProp,
  SLOT_PARITY_COMPONENTS,
  toRegistryId,
} from './lib/storybook-catalog.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const vueIndex = join(root, 'packages/vue/src/index.ts');
const svelteIndex = join(root, 'packages/svelte/src/lib/index.ts');

const generatedCrossDir = join(root, 'apps/playground/cross-framework/generated');
const generatedRegistryDir = join(root, 'apps/playground/.storybook/crossFramework');
const generatedStoriesDir = join(root, 'apps/playground/stories/generated');

mkdirSync(generatedCrossDir, { recursive: true });
mkdirSync(join(generatedRegistryDir, 'registry'), { recursive: true });
mkdirSync(generatedStoriesDir, { recursive: true });

const catalog = buildStorybookCatalog(root);
const auto = catalog.autoScaffold;

function writePackageComponentMap(framework, sources, outFile) {
  /** @type {Map<string, string>} */
  const byName = new Map();
  const outDir = dirname(outFile);
  for (const { indexPath, packageSubpath } of sources) {
    for (const { name, from } of parseDefaultExportPaths(indexPath)) {
      const cleaned = from.replace(/^\.\//, '');
      const absolute = join(root, packageSubpath, cleaned);
      // Generated files live under apps/playground/cross-framework/generated —
      // compute the relative import so depth changes cannot break Storybook.
      const rel = relative(outDir, absolute).split('\\').join('/');
      byName.set(name, rel.startsWith('.') ? rel : `./${rel}`);
    }
  }
  const lines = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/generate-storybook-parity.mjs — do not edit.',
    '',
  ];
  for (const name of [...byName.keys()].sort((a, b) => a.localeCompare(b))) {
    lines.push(`export { default as ${name} } from '${byName.get(name)}';`);
  }
  lines.push('');
  writeFileSync(outFile, lines.join('\n'));
  return byName.size;
}

const vueCount = writePackageComponentMap(
  'vue',
  [
    { indexPath: vueIndex, packageSubpath: 'packages/vue/src' },
    {
      indexPath: join(root, 'packages/vue/src/LiquidGlass/index.ts'),
      packageSubpath: 'packages/vue/src/LiquidGlass',
    },
  ],
  join(generatedCrossDir, 'vuePackageComponents.ts'),
);
const svelteCount = writePackageComponentMap(
  'svelte',
  [
    { indexPath: svelteIndex, packageSubpath: 'packages/svelte/src/lib' },
    {
      indexPath: join(root, 'packages/svelte/src/lib/LiquidGlass/index.ts'),
      packageSubpath: 'packages/svelte/src/lib/LiquidGlass',
    },
  ],
  join(generatedCrossDir, 'sveltePackageComponents.ts'),
);

/** @type {Array<{ name: string; id: string; mode: 'props' | 'slot'; propKeys: string[]; defaultProps: Record<string, unknown>; defaultSlot?: string }>} */
const scaffolds = [];

for (const entry of auto) {
  const contract = readComponentContract(root, entry.name);
  const propKeys = pickSimplePropKeys(contract?.props ?? []);
  const mode = SLOT_PARITY_COMPONENTS.has(entry.name) ? 'slot' : 'props';
  /** @type {Record<string, unknown>} */
  const defaultProps = {};

  for (const prop of contract?.props ?? []) {
    if (!prop?.name) continue;
    if (prop.name === 'children') continue;
    if (!propKeys.includes(prop.name) && !prop.required) continue;
    if (!/^[A-Za-z_$][\w$]*$/.test(prop.name)) continue;
    if (prop.name.startsWith('on')) continue;
    const value = defaultValueForProp(prop, entry.name);
    if (value !== undefined && (prop.required || propKeys.includes(prop.name))) {
      defaultProps[prop.name] = value;
    }
  }

  scaffolds.push({
    name: entry.name,
    id: entry.id,
    mode,
    propKeys,
    defaultProps,
    defaultSlot: mode === 'slot' ? entry.name : undefined,
  });
}

// --- registry/generated.tsx ---
{
  const importNames = [...new Set(scaffolds.map((s) => s.name))].sort();
  const lines = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/generate-storybook-parity.mjs — do not edit.',
    "import type { CrossFrameworkComponentDefinition } from '../types';",
    "import { defineSlotParity, definePropsParity } from '../defineParity';",
    importNames.length
      ? `import {\n  ${importNames.join(',\n  ')},\n} from '@larose-ui/react';`
      : '',
    '',
    'export const generatedRegistry: Record<string, CrossFrameworkComponentDefinition> = {',
  ];

  for (const scaffold of scaffolds) {
    const propKeysLit = JSON.stringify(scaffold.propKeys);
    const defaultPropsLit = JSON.stringify(scaffold.defaultProps);
    if (scaffold.mode === 'slot') {
      lines.push(`  ${scaffold.id}: defineSlotParity({`);
      lines.push(`    id: '${scaffold.id}',`);
      lines.push(`    displayName: '${scaffold.name}',`);
      lines.push(`    defaultSlot: ${JSON.stringify(scaffold.defaultSlot ?? scaffold.name)},`);
      lines.push(`    propKeys: ${propKeysLit},`);
      lines.push(`    defaultProps: ${defaultPropsLit},`);
      lines.push(`    Component: ${scaffold.name},`);
      lines.push('  }),');
    } else {
      lines.push(`  ${scaffold.id}: definePropsParity({`);
      lines.push(`    id: '${scaffold.id}',`);
      lines.push(`    displayName: '${scaffold.name}',`);
      lines.push(`    propKeys: ${propKeysLit},`);
      lines.push(`    defaultProps: ${defaultPropsLit},`);
      lines.push(`    Component: ${scaffold.name},`);
      lines.push('  }),');
    }
    lines.push('');
  }

  lines.push('};');
  lines.push('');
  writeFileSync(join(generatedRegistryDir, 'registry/generated.tsx'), lines.join('\n'));
}

// --- titleRegistry.generated.ts ---
{
  const lines = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/generate-storybook-parity.mjs — do not edit.',
    '',
    'export const GENERATED_STORY_TITLE_CROSS_FRAMEWORK: Record<string, string> = {',
  ];
  for (const scaffold of scaffolds) {
    lines.push(`  'Auto/${scaffold.name}': '${scaffold.id}',`);
  }
  lines.push('};');
  lines.push('');
  writeFileSync(join(generatedRegistryDir, 'titleRegistry.generated.ts'), lines.join('\n'));
}

// --- AutoParity.stories.tsx ---
{
  const importNames = [...new Set(scaffolds.map((s) => s.name))].sort();
  const lines = [
    '/* eslint-disable */',
    '// @ts-nocheck — auto stubs; replace with curated stories when a component graduates.',
    '// AUTO-GENERATED by scripts/generate-storybook-parity.mjs — do not edit.',
    "import type { Meta, StoryObj } from '@storybook/react';",
    importNames.length
      ? `import {\n${importNames.map((n) => `  ${n} as ${n}Component,`).join('\n')}\n} from '@larose-ui/react';`
      : "import type { ComponentType } from 'react';",
    '',
  ];

  if (scaffolds.length === 0) {
    lines.push('const meta: Meta = { title: "Auto/Empty" };');
    lines.push('export default meta;');
    lines.push('export const Placeholder: StoryObj = { render: () => null };');
  } else {
    // Storybook requires one default export per file — generate one story file barrel via multiple metas is invalid.
    // Use a single meta + named stories that render different components via crossFramework param.
    lines.push('/**');
    lines.push(' * Auto-discovered shared components not covered by hand-written stories.');
    lines.push(' * Each export sets `parameters.laRose.crossFramework` for Vue/Svelte mounts.');
    lines.push(' */');
    lines.push('const meta = {');
    lines.push("  title: 'Auto/Discovered',");
    lines.push("  tags: ['autodocs', 'fw-react', 'fw-vue', 'fw-svelte'],");
    lines.push('} satisfies Meta;');
    lines.push('');
    lines.push('export default meta;');
    lines.push('type Story = StoryObj;');
    lines.push('');

    for (const scaffold of scaffolds) {
      const storyName = scaffold.name.replace(/[^A-Za-z0-9]/g, '');
      lines.push(`export const ${storyName}: Story = {`);
      lines.push(`  name: '${scaffold.name}',`);
      lines.push('  parameters: {');
      lines.push('    laRose: {');
      lines.push(`      crossFramework: '${scaffold.id}',`);
      lines.push(`      displayName: '${scaffold.name}',`);
      lines.push('    },');
      lines.push('  },');
      lines.push('  args: {');
      if (scaffold.mode === 'slot') {
        lines.push(`    children: ${JSON.stringify(scaffold.defaultSlot ?? scaffold.name)},`);
      }
      for (const [key, value] of Object.entries(scaffold.defaultProps)) {
        lines.push(`    ${key}: ${JSON.stringify(value)},`);
      }
      lines.push('  },');
      // Alias imports avoid clashing with story export names.
      if (scaffold.mode === 'slot') {
        lines.push(
          `  render: (args) => <${scaffold.name}Component {...args}>{args.children as string}</${scaffold.name}Component>,`,
        );
      } else {
        lines.push(`  render: (args) => <${scaffold.name}Component {...args} />,`);
      }
      lines.push('};');
      lines.push('');
    }
  }

  writeFileSync(join(generatedStoriesDir, 'AutoParity.stories.tsx'), lines.join('\n'));
}

// ─── Curated story parity sync ────────────────────────────────────────────────
//
// For every curated story file under apps/playground/stories/ that:
//   1. Declares title: 'Foundation/<Name>' (or similar prefix)
//   2. Has a matching component exported from ALL three packages
//   3. Is NOT already tagged fw-vue + fw-svelte
//
// We:
//   A. Patch the story file: add fw-vue + fw-svelte to tags, add crossFramework param
//   B. Add a generated entry to titleRegistry.generated.ts (Foundation prefix)
//   C. Add a basic parity entry to registry/generated.tsx (if not already hand-written)
//
// This runs automatically when contributors run `pnpm generate-storybook-parity`
// (or `make parity-sync`) after exporting a new component from all three index files.

const storiesDir = join(root, 'apps/playground/stories');

/**
 * Build component name → absolute path maps for each framework from the
 * already-generated component map files (authoritative after this run).
 */
function buildComponentSets() {
  const vueSrc = readFileSync(join(generatedCrossDir, 'vuePackageComponents.ts'), 'utf8');
  const svelteSrc = readFileSync(join(generatedCrossDir, 'sveltePackageComponents.ts'), 'utf8');
  const vueNames = new Set([...vueSrc.matchAll(/export \{ default as (\w+) \}/g)].map((m) => m[1]));
  const svelteNames = new Set([...svelteSrc.matchAll(/export \{ default as (\w+) \}/g)].map((m) => m[1]));
  return { vueNames, svelteNames };
}

/**
 * Scan a story file and return its meta title + whether it's already tagged for
 * each framework.
 * @param {string} src
 * @returns {{ title: string | null; hasFwVue: boolean; hasFwSvelte: boolean; hasCrossFramework: boolean }}
 */
function parseStoryMeta(src) {
  const titleMatch = src.match(/title:\s*['"]([^'"]+)['"]/);
  const title = titleMatch ? titleMatch[1] : null;
  // Look for fw-vue / fw-svelte tags only in the meta tags array (not per-story overrides)
  const metaBlock = src.match(/^export default[^;]+;/ms)?.[0] ?? src.slice(0, 600);
  const hasFwVue = /['"]fw-vue['"]/.test(metaBlock);
  const hasFwSvelte = /['"]fw-svelte['"]/.test(metaBlock);
  const hasCrossFramework = /crossFramework:/.test(src);
  return { title, hasFwVue, hasFwSvelte, hasCrossFramework };
}

/**
 * Patch a story file in place to add fw-vue + fw-svelte tags and a
 * crossFramework: '<id>' param when missing. Returns true if modified.
 * @param {string} filePath
 * @param {string} registryId
 * @returns {boolean}
 */
function patchStoryFile(filePath, registryId) {
  let src = readFileSync(filePath, 'utf8');
  let modified = false;

  // 1. Add fw-vue / fw-svelte to the meta-level tags array
  //    Match the first tags: [...] that doesn't already contain fw-vue
  if (!/['"]fw-vue['"]/.test(src.slice(0, src.indexOf('export const ') < 0 ? src.length : src.indexOf('export const ')))) {
    src = src.replace(
      /(tags:\s*\[)([^\]]*?)(\])/,
      (_, open, inner, close) => {
        const existing = inner.trim();
        const additions = ["'fw-vue'", "'fw-svelte'"]
          .filter((tag) => !inner.includes(tag))
          .join(', ');
        return additions
          ? `${open}${existing}${existing ? ', ' : ''}${additions}${close}`
          : `${open}${inner}${close}`;
      },
    );
    modified = true;
  }

  // 2. Add crossFramework param inside the first parameters: { ... } block (meta level)
  if (!/crossFramework:/.test(src)) {
    src = src.replace(
      /(\bparameters:\s*\{)/,
      `$1\n    laRose: { crossFramework: '${registryId}' },`,
    );
    modified = true;
  }

  if (modified) {
    writeFileSync(filePath, src);
  }
  return modified;
}

const { vueNames, svelteNames } = buildComponentSets();

// STORY_TITLE_CROSS_FRAMEWORK from hand-written titleRegistry.ts (to avoid duplicating)
const titleRegistrySrc = readFileSync(join(root, 'apps/playground/.storybook/crossFramework/titleRegistry.ts'), 'utf8');
const alreadyMappedTitles = new Set(
  [...titleRegistrySrc.matchAll(/'([^']+)':\s*'([^']+)'/g)].map((m) => m[1]),
);

/** Curated story → registry id pairs that we discover in this run */
const curatedPairs = [];
let patchCount = 0;

for (const file of readdirSync(storiesDir).sort()) {
  if (!file.endsWith('.stories.tsx')) continue;
  const filePath = join(storiesDir, file);
  const src = readFileSync(filePath, 'utf8');
  const { title, hasFwVue, hasFwSvelte, hasCrossFramework } = parseStoryMeta(src);

  if (!title) continue;

  // Extract component name from title: 'Foundation/Activity' → 'Activity'
  const titleParts = title.split('/');
  const componentName = titleParts[titleParts.length - 1].replace(/\s+/g, '');
  if (!componentName) continue;

  // Must exist in all three packages
  if (!vueNames.has(componentName) || !svelteNames.has(componentName)) continue;

  const registryId = toRegistryId(componentName);

  // Track for titleRegistry.generated.ts even if already tagged
  if (!alreadyMappedTitles.has(title)) {
    curatedPairs.push({ title, id: registryId });
  }

  // Only patch if not already fully wired
  if (!hasFwVue || !hasFwSvelte || !hasCrossFramework) {
    const patched = patchStoryFile(filePath, registryId);
    if (patched) patchCount++;
  }
}

// --- titleRegistry.generated.ts (extended with curated Foundation stories) ---
{
  const lines = [
    '/* eslint-disable */',
    '// AUTO-GENERATED by scripts/generate-storybook-parity.mjs — do not edit.',
    '',
    'export const GENERATED_STORY_TITLE_CROSS_FRAMEWORK: Record<string, string> = {',
  ];
  // Original auto scaffold entries
  for (const scaffold of scaffolds) {
    lines.push(`  'Auto/${scaffold.name}': '${scaffold.id}',`);
  }
  // Newly discovered curated stories
  if (curatedPairs.length) {
    lines.push('  // Curated Foundation stories auto-detected via parity-sync:');
    for (const { title, id } of curatedPairs.sort((a, b) => a.title.localeCompare(b.title))) {
      lines.push(`  '${title}': '${id}',`);
    }
  }
  lines.push('};');
  lines.push('');
  writeFileSync(join(generatedRegistryDir, 'titleRegistry.generated.ts'), lines.join('\n'));
}

// --- catalog.json ---
writeFileSync(
  join(generatedRegistryDir, 'catalog.json'),
  `${JSON.stringify(
    {
      ...catalog,
      generated: {
        vuePackageComponents: vueCount,
        sveltePackageComponents: svelteCount,
        autoRegistryEntries: scaffolds.length,
        curatedParityPatched: patchCount,
        curatedTitleEntries: curatedPairs.length,
        scaffolds: scaffolds.map((s) => ({ id: s.id, name: s.name, mode: s.mode })),
      },
    },
    null,
    2,
  )}\n`,
);

console.log(
  `[larose] storybook parity: vue=${vueCount} svelte=${svelteCount} autoRegistry=${scaffolds.length} curatedPatched=${patchCount} newTitleEntries=${curatedPairs.length} uncoveredRoots=${catalog.uncoveredRootCount}`,
);
